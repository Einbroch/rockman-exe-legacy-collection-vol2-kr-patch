def has_batchim(s):
    ch = s.rstrip(' *')[-1]
    if '가' <= ch <= '힣':
        return (ord(ch) - 0xAC00) % 28 != 0
    return ch in '0136781LMNRlmnr'   # 숫자·영문 끝은 읽는 소리로


def name(n, gl):
    """이름(코드 글자 포함 가능: '포르테 F')."""
    m = re.match(r'^(.*?)(\s+[A-Z*])$', n)
    base, code = (m.group(1), m.group(2)) if m else (n, '')
    if base in NAMES:
        return NAMES[base] + code
    s = SUFFIX.match(base)
    if s and (s.group(1) in NAMES or s.group(1) in gl):
        return (NAMES.get(s.group(1)) or gl[s.group(1)]) + s.group(2) + code
    if base in gl:
        return gl[base] + code
    raise KeyError(base)


def effect_term(t):
    t = t.strip()
    for jp, ko in EFFECT_TAIL:
        if t.endswith(jp):
            return effect_term(t[:-len(jp)]) + ko
    m = re.match(r'^(.*?)([+\-×]\d+%?)$', t)
    if m and m.group(1) in EFFECT:
        return EFFECT[m.group(1)] + m.group(2)
    if re.match(r'^HP[+\-]\d+%?$', t):
        return t
    if t in EFFECT:
        return EFFECT[t]
    raise KeyError(t)


def effects(s):
    return NL.join(' / '.join(effect_term(t) for t in line.split(' / ')) for line in s.split(NL))


