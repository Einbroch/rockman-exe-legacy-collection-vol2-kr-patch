MANUAL = {**MUSIC, **CHIPS, **NAVICUST, **GREET, **TROPHY}
JA = re.compile('[ぁ-ヿ一-鿿]')


def loose(s):
    return re.sub(r'(&#xA;|\s|　)', '', s.translate(FW))


def art(jp):
    s = jp
    for k in sorted(ART_TERMS, key=len, reverse=True):
        s = s.replace(k, ART_TERMS[k])
    return s


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    rows = json.loads((ROOT / 'work' / 'gallery_src.json').read_text(encoding='utf-8'))
    lc = json.loads((ROOT / 'work' / 'lc_jp_ko.json').read_text(encoding='utf-8'))
    lcl = {}
    for k, v in lc.items():
        lcl.setdefault(loose(k), v)
    manual_l = {loose(k): v for k, v in MANUAL.items()}
    out, left = [], []
    for r in rows:
        if r['doc'] not in VOL1_DOCS:
            continue
        jp = r['jp']
        ko = MANUAL.get(jp) or manual_l.get(loose(jp)) or lcl.get(loose(jp))
        if ko is None and r['doc'] == '0x39652fc':
            ko = art(jp)
        if ko is not None:
            ko = ko.replace('十자', '십자')   # 한글 롬의 「十자」 기호는 런처 글꼴에선 한자로 보인다
        if ko is None or JA.search(ko):
            left.append((r['doc'], jp, ko))
            continue
        ko = ko.replace('\\n', NL).replace('、', ', ')
        ko = re.sub(r'&(?!#xA;|amp;)', '&amp;', ko)
        out.append({'off': r['off'], 'cht': r['cht'], 'ko': ko})
    (ROOT / 'tools' / 'launcher_gallery_ko.json').write_text(json.dumps(out, ensure_ascii=False, indent=0), encoding='utf-8')
    print('번역', len(out), '남음', len(left))
    for x in left[:40]:
        print(' ', x)
    return not left


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
